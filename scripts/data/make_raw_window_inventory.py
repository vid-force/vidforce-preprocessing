#!/usr/bin/env python3
"""Window inventory of a raw Hoi! release.

Lists, for every recording session, the confirmed interaction windows of each embodiment (from the release's
``interaction_splitting_info_<session>_confirmed.json`` files), the third-person cameras that recorded it, and the
windows performed by both embodiments. Everything downstream derives from this file.

  python scripts/data/make_raw_window_inventory.py --root $HOI_ROOT --out window_inventory.json --date YYYY-MM-DD
  python scripts/data/make_raw_window_inventory.py --root $HOI_ROOT --date YYYY-MM-DD --check window_inventory.json
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys


def trial_windows(confirmed: pathlib.Path) -> list[str]:
    try:
        payload = json.loads(confirmed.read_text())
    except (OSError, ValueError):
        return []
    return sorted((w for w in payload
                   if isinstance(w, str) and w.startswith("window_")),
                  key=lambda w: int(w.split("_")[1]))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--root", type=pathlib.Path, required=True,
                    help="root of the raw Hoi! release")
    ap.add_argument("--out", type=pathlib.Path,
                    default=pathlib.Path("window_inventory.json"))
    ap.add_argument("--date", required=True,
                    help="generation date stamp YYYY-MM-DD")
    ap.add_argument("--check", type=pathlib.Path, default=None,
                    help="compare the regenerated 'trials' block against this stored inventory instead of writing")
    a = ap.parse_args(argv)

    trials: dict[str, dict] = {}
    for scene_dir in sorted(p for p in a.root.iterdir() if p.is_dir()
                            and not p.name.startswith("_")):
        scene = scene_dir.name
        for emb in ("hand", "gripper"):
            emb_dir = scene_dir / emb
            if not emb_dir.is_dir():
                continue
            for cj in sorted(emb_dir.glob(
                    "interaction_splitting_info_*_confirmed.json")):
                m = re.match(r"interaction_splitting_info_(.+)_confirmed",
                             cj.name)
                trial = m.group(1)
                windows = trial_windows(cj)
                views = sorted(
                    v.name for v in emb_dir.iterdir()
                    if v.is_dir() and v.name.startswith("iphone")
                    and (v / f"{scene}_{trial}_{emb}"
                         / "camera_rgb.zip").exists())
                if not windows or not views:
                    continue
                t = trials.setdefault(f"{scene}|{trial}", {})
                t[f"{emb}_windows"] = windows
                t[f"{emb}_views"] = views
    for t in trials.values():
        t["paired_windows"] = sorted(
            set(t.get("gripper_windows", []))
            & set(t.get("hand_windows", [])),
            key=lambda w: int(w.split("_")[1]))
        t.setdefault("gripper_windows", [])
        t.setdefault("hand_windows", [])
        t.setdefault("gripper_views", [])
        t.setdefault("hand_views", [])

    n_g = sum(len(t["gripper_windows"]) for t in trials.values())
    n_h = sum(len(t["hand_windows"]) for t in trials.values())
    n_p = sum(len(t["paired_windows"]) for t in trials.values())
    print(f"trials: {len(trials)}; windows gripper {n_g} / hand {n_h} "
          f"/ paired {n_p}")

    if a.check:
        ref = json.loads(a.check.read_text())["trials"]
        norm = lambda d: {k: {kk: sorted(vv) for kk, vv in v.items()}
                          for k, v in d.items()}
        if norm(ref) == norm(trials):
            print("CHECK_OK: regenerated inventory matches", a.check)
            return 0
        for k in sorted(set(ref) | set(trials)):
            if ref.get(k) != trials.get(k):
                print("  DIFF", k)
                for kk in set(ref.get(k, {})) | set(trials.get(k, {})):
                    rv, tv = ref.get(k, {}).get(kk), trials.get(k, {}).get(kk)
                    if rv != tv:
                        print(f"    {kk}: stored={rv} regenerated={tv}")
        print("CHECK_FAILED")
        return 1

    out = {"meta": {
        "source": "interaction_splitting_info_*_confirmed.json + per-trial "
                  "iphone camera_rgb.zip presence, regenerated by "
                  "make_raw_window_inventory.py",
        "root": str(a.root), "date": a.date,
    }, "trials": dict(sorted(trials.items()))}
    a.out.write_text(json.dumps(out, indent=1))
    print("WROTE", a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
